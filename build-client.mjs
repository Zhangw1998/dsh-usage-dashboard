#!/usr/bin/env node
/**
 * 把 view-model.js 与 chart-kit.js 内联进 client.js。
 *
 * 为什么需要：DSH 的客户端插件是**逐字**把 client.js 拼进一个 combo bundle 再用
 * `factory(require)` 执行的，没有任何 ESM 解析。所以 client.js 只能是一个自包含文件，
 * 不能 import 同级模块。这里做一次纯文本注入：
 *   - 源文件仍保持模块化、可被 node --test 直接测试；
 *   - 构建产物 client.js 顶部多出一段内联实现，行为与源文件一致。
 *
 * 幂等：每次运行都先剥掉上一次注入的标记区间再重新插入。
 */
import { readFileSync, writeFileSync } from 'node:fs'
import { dirname, join } from 'node:path'
import { fileURLToPath } from 'node:url'

const here = dirname(fileURLToPath(import.meta.url))
const read = name => readFileSync(join(here, name), 'utf8')

const BEGIN = '/* ===== BEGIN INLINED MODULES (generated by build-client.mjs) ===== */'
const END = '/* ===== END INLINED MODULES ===== */'

/** 把 ESM 模块转成可在 factory 作用域内使用的对象：去掉 export 关键字 */
function inline(name, source) {
  const body = source
    // 去掉 import 语句（内联后不存在模块边界）
    .replace(/^import[^\n]*\n/gm, '')
    // export function / export const / export class -> 普通声明
    .replace(/^export\s+(function|const|let|class|async function)/gm, '$1')
    // export { ... } 集体导出
    .replace(/^export\s*\{[^}]*\};?\s*$/gm, '')
  return `// ---- inlined: ${name} ----\n${body.trim()}\n`
}

let client = read('client.js')

// 1) 剥掉旧的内联区间
const b = client.indexOf(BEGIN)
if (b !== -1) {
  const e = client.indexOf(END)
  if (e === -1) throw new Error('corrupt inline block: BEGIN without END')
  client = client.slice(0, b) + client.slice(e + END.length).replace(/^\n+/, '')
}

// 2) 组装内联块。注意：view-model 与 components 必须在 factory 内可见，
//    因此插在 `factory(require) {` 之后的第一行。
const block = [
  '',
  BEGIN,
  inline('view-model.js', read('view-model.js')),
  inline('chart-kit.js', read('chart-kit.js')),
  END,
  '',
].join('\n')

const anchor = /\n(\s*)factory\(require\) \{\n/.exec(client)
if (!anchor) throw new Error('client.js: factory(require) { not found')
const at = anchor.index + anchor[0].length
client = client.slice(0, at) + block + client.slice(at)

writeFileSync(join(here, 'client.js'), client)
console.log('inlined view-model.js + chart-kit.js into client.js')
